name = 'Saurav'

# Length of string
print(len(name))

# String slicing [start:end]
name_short = name[2:4]
print(name_short)

# Minus indexing
nameshort = name[-4:-1]
print(nameshort)

print(name[:4])
print(name[0:])

# Slicing with skip value
num = "123456789"

print(num[1:5:2])

# Escape sequences

print("Hello\nSaurav")
print("Hello\tSaurav")
print("He said \"Hello\"")
print("It's Python")